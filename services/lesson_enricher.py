from copy import deepcopy

THEORY_TARGET_LENGTH = 900


def _is_short_theory(text: str) -> bool:
    normalized = str(text or "").strip()
    return len(normalized) < THEORY_TARGET_LENGTH


def _build_practicum_theory(topic: str, source_text: str) -> str:
    core = str(source_text or "").strip()
    return (
        "📘 Теория в формате практикума\n\n"
        f"Тема: {topic}. Ниже — разбор как на учебном спринте: от контекста к действию.\n\n"
        "1) Зачем это изучаем\n"
        "На практике ошибки в этой теме обычно приводят к двум проблемам: команда делает лишние фичи "
        "и не может доказать влияние на продуктовые метрики. Поэтому цель — научиться формулировать решения "
        "через проблему, сегмент, ожидаемый результат и критерии проверки.\n\n"
        "2) Базовая модель мышления\n"
        "Используй связку: 'ситуация → мотивация → действие → измеримый эффект'. "
        "Сначала фиксируем конкретный контекст пользователя, затем причину поведения, потом продуктовый шаг, "
        "и только после этого — метрику успеха. Такой порядок снижает риск абстракций и помогает быстрее валидировать гипотезы.\n\n"
        "3) Как применять в реальном продукте\n"
        "- Определи один узкий сегмент, а не 'всех пользователей'.\n"
        "- Сформулируй одну главную боль в конкретной ситуации.\n"
        "- Предложи решение в формате проверяемой гипотезы.\n"
        "- Добавь success-метрику и guardrail-метрику, чтобы не сломать соседние сценарии.\n\n"
        "4) Частые ошибки новичков\n"
        "- Формулировка уровня 'улучшим UX' без сценария и цифр.\n"
        "- Подмена проблемы списком фич.\n"
        "- Отсутствие критериев, по которым можно понять, сработало ли решение.\n\n"
        "5) Мини-кейс\n"
        "Представь, что пользователи долго доходят до первого ценного действия. Вместо общего вывода 'нужно упростить онбординг' "
        "мы уточняем: кто именно отваливается, на каком шаге, из-за какой неопределенности, и какой целевой сдвиг в метрике "
        "должны получить после изменения. Тогда команда понимает не только что делать, но и как проверить результат.\n\n"
        "Короткий конспект исходной версии урока:\n"
        f"{core}"
    )


def enrich_lesson_for_clarity(lesson: dict) -> dict:
    lesson = deepcopy(lesson or {})
    topic = lesson.get("title", "Тема урока")
    blocks = lesson.get("blocks", [])

    for block in blocks:
        if str(block.get("type", "")).lower() == "theory":
            theory_text = block.get("text", "")
            if _is_short_theory(theory_text):
                block["text"] = _build_practicum_theory(topic, theory_text)
            break

    lesson["blocks"] = blocks
    return lesson
